CREATE TABLE referent_availability (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 referent_id BIGINT NOT NULL REFERENCES referent_profiles(id) ON DELETE CASCADE,
 starts_on DATE NOT NULL, ends_on DATE NOT NULL,
 kind TEXT NOT NULL CHECK(kind IN ('available','blocked')),
 note TEXT NOT NULL DEFAULT '',
 created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL,
 CHECK(ends_on>=starts_on)
);
CREATE INDEX referent_availability_range ON referent_availability(referent_id,starts_on);
CREATE TABLE referent_appointments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 referent_id BIGINT NOT NULL REFERENCES referent_profiles(id) ON DELETE CASCADE,
 seminar_id BIGINT REFERENCES seminars(id) ON DELETE SET NULL,
 title TEXT NOT NULL, location TEXT NOT NULL DEFAULT '', day DATE NOT NULL,
 state TEXT NOT NULL CHECK(state IN ('proposed','confirmed','declined','cancelled')),
 source TEXT NOT NULL CHECK(source IN ('referent','admin')),
 note TEXT NOT NULL DEFAULT '',
 created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 decided_by BIGINT REFERENCES users(id) ON DELETE SET NULL, decided_at BIGINT,
 created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL
);
CREATE INDEX referent_appointments_day ON referent_appointments(referent_id,day);
CREATE INDEX referent_appointments_state ON referent_appointments(state,day);
CREATE TABLE calendar_reminders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_key TEXT NOT NULL UNIQUE,
 referent_id BIGINT NOT NULL REFERENCES referent_profiles(id) ON DELETE CASCADE,
 period TEXT NOT NULL, recipient TEXT NOT NULL,
 status TEXT NOT NULL CHECK(status IN ('queued','submitted','blocked','ambiguous')),
 message_id TEXT NOT NULL UNIQUE, created_at BIGINT NOT NULL, submitted_at BIGINT, last_error_redacted TEXT
);
CREATE INDEX calendar_reminders_period ON calendar_reminders(period,referent_id);
