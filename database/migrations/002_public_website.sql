CREATE TABLE seminar_categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, slug TEXT NOT NULL UNIQUE, name TEXT NOT NULL, position INTEGER NOT NULL DEFAULT 0
);
