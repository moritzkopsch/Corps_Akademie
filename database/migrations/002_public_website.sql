CREATE TABLE referent_profiles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT UNIQUE REFERENCES users(id) ON DELETE SET NULL,
 slug TEXT NOT NULL UNIQUE, name TEXT NOT NULL, headline TEXT NOT NULL, corps TEXT NOT NULL DEFAULT '',
 biography TEXT NOT NULL, expertise_json JSONB NOT NULL,
 status TEXT NOT NULL CHECK(status IN ('draft','published','inactive','archived')),
 source_url TEXT NOT NULL DEFAULT '', row_version INTEGER NOT NULL DEFAULT 1,
 created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL
);
CREATE TABLE seminars (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, slug TEXT NOT NULL UNIQUE, title TEXT NOT NULL,
 category_id BIGINT NOT NULL REFERENCES seminar_categories(id) ON DELETE RESTRICT,
 summary TEXT NOT NULL, description TEXT NOT NULL, benefits_json JSONB NOT NULL,
 audience TEXT NOT NULL, duration TEXT NOT NULL, format TEXT NOT NULL DEFAULT 'Nach Vereinbarung',
 status TEXT NOT NULL CHECK(status IN ('draft','published','inactive','archived')),
 featured INTEGER NOT NULL DEFAULT 0 CHECK(featured IN (0,1)), source_url TEXT NOT NULL DEFAULT '',
 row_version INTEGER NOT NULL DEFAULT 1, created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL
);
CREATE INDEX seminars_public ON seminars(status,category_id);
CREATE TABLE seminar_referents (
 seminar_id BIGINT NOT NULL REFERENCES seminars(id) ON DELETE CASCADE,
 referent_id BIGINT NOT NULL REFERENCES referent_profiles(id) ON DELETE CASCADE,
 PRIMARY KEY(seminar_id,referent_id)
);
CREATE TABLE public_inquiries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, public_id TEXT NOT NULL UNIQUE, submission_hash TEXT NOT NULL UNIQUE,
 kind TEXT NOT NULL CHECK(kind IN ('seminar','contact')),
 seminar_id BIGINT REFERENCES seminars(id) ON DELETE RESTRICT,
 email TEXT NOT NULL, email_key TEXT NOT NULL, details_ciphertext TEXT NOT NULL, key_id TEXT NOT NULL,
 state TEXT NOT NULL CHECK(state IN ('unverified','received','in_progress','closed')),
 consent_version TEXT NOT NULL, verified_at BIGINT, created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL,
 CHECK((kind='seminar' AND seminar_id IS NOT NULL) OR (kind='contact' AND seminar_id IS NULL))
);
CREATE INDEX inquiries_state ON public_inquiries(state,created_at);
CREATE TABLE newsletter_subscribers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT NOT NULL, email_key TEXT NOT NULL UNIQUE,
 state TEXT NOT NULL CHECK(state IN ('pending','active','unsubscribed')),
 consent_version TEXT NOT NULL, requested_at BIGINT NOT NULL, confirmed_at BIGINT, unsubscribed_at BIGINT
);
CREATE TABLE public_tokens (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, token_hash TEXT NOT NULL UNIQUE,
 purpose TEXT NOT NULL CHECK(purpose IN ('inquiry_verify','newsletter_confirm','newsletter_unsubscribe')),
 inquiry_id BIGINT REFERENCES public_inquiries(id) ON DELETE CASCADE,
 subscriber_id BIGINT REFERENCES newsletter_subscribers(id) ON DELETE CASCADE,
 expires_at BIGINT NOT NULL, consumed_at BIGINT, revoked_at BIGINT, created_at BIGINT NOT NULL,
 CHECK((purpose='inquiry_verify' AND inquiry_id IS NOT NULL AND subscriber_id IS NULL)
 OR (purpose IN ('newsletter_confirm','newsletter_unsubscribe') AND inquiry_id IS NULL AND subscriber_id IS NOT NULL))
);
CREATE TABLE public_mail_outbox (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_key TEXT NOT NULL UNIQUE,
 token_id BIGINT REFERENCES public_tokens(id) ON DELETE CASCADE,
 recipient TEXT NOT NULL, payload_ciphertext TEXT, key_id TEXT NOT NULL,
 status TEXT NOT NULL CHECK(status IN ('queued','sending','submitted','cancelled','blocked','ambiguous')),
 message_id TEXT NOT NULL UNIQUE, lease_token TEXT, lease_until BIGINT,
 created_at BIGINT NOT NULL, submitted_at BIGINT, last_error_redacted TEXT
);
CREATE INDEX public_mail_due ON public_mail_outbox(status,id);
