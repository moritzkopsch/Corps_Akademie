ALTER TABLE newsletter_subscribers ADD COLUMN subscription_version INTEGER NOT NULL DEFAULT 1;
CREATE TABLE newsletter_campaigns (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, subject TEXT NOT NULL, body TEXT NOT NULL,
 state TEXT NOT NULL CHECK(state IN ('draft','queued','completed','cancelled')),
 row_version INTEGER NOT NULL DEFAULT 1,
 created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT, created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL, queued_at BIGINT
);
CREATE TABLE newsletter_deliveries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, campaign_id BIGINT NOT NULL REFERENCES newsletter_campaigns(id) ON DELETE RESTRICT,
 subscriber_id BIGINT NOT NULL REFERENCES newsletter_subscribers(id) ON DELETE RESTRICT, subscription_version INTEGER NOT NULL,
 state TEXT NOT NULL CHECK(state IN ('queued','sending','submitted','cancelled','ambiguous','blocked')),
 unsubscribe_hash TEXT UNIQUE,
 message_id TEXT NOT NULL UNIQUE, lease_token TEXT, lease_until BIGINT, submitted_at BIGINT, error_type TEXT,
 UNIQUE(campaign_id,subscriber_id)
);
CREATE INDEX newsletter_due ON newsletter_deliveries(state,id);
