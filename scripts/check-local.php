<?php
declare(strict_types=1);

// Development diagnostics only; this is not the application's installer.
if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

require dirname(__DIR__) . '/app/Infrastructure/Config.php';
$checks = ['PHP mit Sicherheitskorrekturen (8.2.35/8.3.36/8.4.27/8.5.12)' => \Corpsakademie\Infrastructure\Config::runtimeSupported(PHP_VERSION)];
printf("PHP %s\n", PHP_VERSION);
foreach (['pdo_pgsql', 'mbstring', 'intl', 'fileinfo', 'openssl', 'sodium', 'gd', 'dom', 'xml', 'curl', 'zip'] as $extension) {
    $checks['Erweiterung ' . $extension] = extension_loaded($extension);
}
$checks['Argon2id verfügbar'] = defined('PASSWORD_ARGON2ID');
$checks['Prüfprozesse verfügbar'] = function_exists('proc_open');

// Connection is taken from the standard libpq environment (PGHOST, PGPORT, PGDATABASE, PGUSER, PGPASSWORD).
$host = (string) (getenv('PGHOST') ?: '127.0.0.1');
$port = (string) (getenv('PGPORT') ?: '5432');
$name = (string) (getenv('PGDATABASE') ?: 'postgres');
$user = (string) (getenv('PGUSER') ?: '');
$password = (string) (getenv('PGPASSWORD') ?: '');
$dsn = sprintf('pgsql:host=%s;port=%s;dbname=%s', $host, $port, $name);

$temporaryDirectory = null;
$db = null;
$second = null;
$schema = 'corps_probe_' . bin2hex(random_bytes(4));
try {
    if (in_array(false, $checks, true)) {
        throw new RuntimeException('Die Voraussetzungen für die Datenbankprüfung fehlen.');
    }
    umask(0077);
    $temporaryDirectory = sys_get_temp_dir() . '/corpsakademie-probe-' . bin2hex(random_bytes(8));
    if (!mkdir($temporaryDirectory, 0700)) {
        throw new RuntimeException('Temporärer Prüfpfad konnte nicht erstellt werden.');
    }
    $options = [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION];
    $db = new PDO($dsn, $user, $password, $options);
    $version = (string) $db->query('SHOW server_version')->fetchColumn();
    printf("PostgreSQL %s über PHP\n", $version);
    $checks['PostgreSQL mindestens 10'] = version_compare($version, '10', '>=');
    $checks['jsonb verfügbar'] = $db->query("SELECT '{\"probe\":true}'::jsonb->>'probe'")->fetchColumn() === 'true';
    $checks['Probeschema erstellt'] = $db->exec('CREATE SCHEMA ' . $schema) !== false;
    $db->exec('SET search_path TO ' . $schema);
    $db->exec('CREATE TABLE probe_parent (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)');
    $db->exec('CREATE TABLE probe_child (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, parent_id BIGINT NOT NULL REFERENCES probe_parent(id))');
    $checks['Identitätsspalte funktioniert'] = (int) $db->query('INSERT INTO probe_parent DEFAULT VALUES RETURNING id')->fetchColumn() === 1;
    $checks['Ungültiger Fremdschlüssel abgewiesen'] = false;
    try {
        $db->exec('INSERT INTO probe_child(parent_id) VALUES (999)');
    } catch (PDOException $error) {
        $checks['Ungültiger Fremdschlüssel abgewiesen'] = ($error->errorInfo[0] ?? null) === '23503';
    }

    $second = new PDO($dsn, $user, $password, $options);
    $second->exec('SET search_path TO ' . $schema);
    $second->exec("SET lock_timeout='200ms'");
    $db->beginTransaction();
    $db->exec('UPDATE probe_parent SET id=id WHERE id=1');
    $checks['Sperrkonflikt wird erkannt'] = false;
    try {
        $second->query('SELECT * FROM probe_parent WHERE id=1 FOR UPDATE')->fetchAll();
    } catch (PDOException $error) {
        $checks['Sperrkonflikt wird erkannt'] = ($error->errorInfo[0] ?? null) === '55P03';
    }
    $checks['SKIP LOCKED überspringt gesperrte Zeile'] = $second->query('SELECT * FROM probe_parent WHERE id=1 FOR UPDATE SKIP LOCKED')->fetchAll() === [];
    $db->rollBack();
    $checks['Rollback erfolgreich'] = (int) $db->query('SELECT count(*) FROM probe_child')->fetchColumn() === 0;

    $backup = $temporaryDirectory . '/probe.sql';
    $process = proc_open(['pg_dump', '--host=' . $host, '--port=' . $port, '--username=' . $user, '--dbname=' . $name, '--no-owner', '--no-privileges', '--format=plain', '--file=' . $backup], [
        0 => ['file', '/dev/null', 'r'], 1 => ['pipe', 'w'], 2 => ['pipe', 'w'],
    ], $pipes, null, ['PATH' => (string) getenv('PATH'), 'PGPASSWORD' => $password, 'LANG' => 'C', 'LC_ALL' => 'C'], ['bypass_shell' => true]);
    if (!is_resource($process)) {
        throw new RuntimeException('pg_dump konnte nicht gestartet werden.');
    }
    stream_get_contents($pipes[1]);
    $dumpErrors = stream_get_contents($pipes[2]);
    fclose($pipes[1]);
    fclose($pipes[2]);
    $checks['pg_dump erfolgreich'] = proc_close($process) === 0 && is_file($backup) && str_contains((string) file_get_contents($backup), 'PostgreSQL database dump complete');
    if (!$checks['pg_dump erfolgreich']) {
        fwrite(STDERR, $dumpErrors . PHP_EOL);
    }
} catch (Throwable $error) {
    $checks['Datenbankprüfung abgeschlossen'] = false;
    fwrite(STDERR, $error->getMessage() . PHP_EOL);
} finally {
    if ($db instanceof PDO) {
        if ($db->inTransaction()) {
            $db->rollBack();
        }
        try {
            $db->exec('DROP SCHEMA IF EXISTS ' . $schema . ' CASCADE');
        } catch (Throwable) {
        }
    }
    $second = null;
    $db = null;
    if ($temporaryDirectory !== null && is_dir($temporaryDirectory)) {
        foreach (glob($temporaryDirectory . '/*') ?: [] as $probeFile) {
            unlink($probeFile);
        }
        rmdir($temporaryDirectory);
    }
}

foreach ($checks as $label => $passed) {
    printf("[%s] %s\n", $passed ? 'OK' : 'FEHLER', $label);
}
echo "Geprüft wird die lokale Umgebung; fachliche Anwendungstests folgen separat.\n";
exit(in_array(false, $checks, true) ? 1 : 0);
